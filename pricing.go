// provinceCities 省份→城市列表 (包含"默认"选项)
// cityPriceMap 省份/城市→PriceEntry
var (
	provinceCities = make(map[string][]string)
	cityPriceMap   = make(map[string]PriceEntry)
)

func init() {
	for _, e := range priceData {
		key := e.Province + "/" + e.City
		cityPriceMap[key] = e
		provinceCities[e.Province] = append(provinceCities[e.Province], e.City)
	}
}

// GetCities 获取某省份的城市列表
func GetCities(province string) []string {
	return provinceCities[province]
}

// GetPrice 获取指定省份/城市的报价
func GetPrice(province, city string) (PriceEntry, bool) {
	p, ok := cityPriceMap[province+"/"+city]
	return p, ok
}

// GetPriceDefault 获取报价，找不到城市时回退到省份默认
func GetPriceDefault(province, city string) PriceEntry {
	if p, ok := GetPrice(province, city); ok {
		return p
	}
	if p, ok := GetPrice(province, "默认"); ok {
		return p
	}
	return PriceEntry{}
}

// CalcBsCost 计费重(kg) → 百世运费(元)，全重单价（不低于最低收费）
func CalcBsCost(weight float64, p PriceEntry) float64 {
	if weight <= 0 {
		return 0
	}
	weight = math.Ceil(weight)
	if weight <= 30 {
		return p.Base30
	}

	// 全重 × 对应档位单价
	var rate float64
	switch {
	case weight <= 70:
		rate = p.R30_70
	case weight <= 300:
		rate = p.R70_300
	case weight <= 1000:
		rate = p.R300_1k
	default:
		rate = p.R1kPlus
	}

	cost := weight * rate
	// 不低于最低收费
	if cost < p.Base30 {
		return p.Base30
	}
	return cost
}

